// 이름으로 시군구코드 검색 (자동완성용)
function searchSigungu(query) {
  if (!query || query.trim().length < 1) return [];
  const q = query.trim();
  return SIGUNGU_CODES.filter(item =>
    item.sido.includes(q) || item.sgg.includes(q) || (item.sido + " " + item.sgg).includes(q)
  ).slice(0, 20);
}

// 코드로 정확히 조회
function getSigunguByCode(code) {
  return SIGUNGU_CODES.find(item => item.code === code) || null;
}

